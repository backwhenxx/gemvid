def check(text: str):
    out = []
    for m in re.finditer(r"[А-Яа-яЁё́-]+", text):
        w = m.group(0)
        if ACC in w:
            continue
        k = w.lower().replace('ё', 'е')
        if k in RISKY:
            out.append((w, RISKY[k]))
        # числа словами тоже часто путает
        elif re.fullmatch(r'(двадцат|тридцат|сорок|пятидесят|шестидесят|семидесят|восьмидесят|девяност|сот|тысяч)\w*', k) and len(k) > 7:
            out.append((w, 'число словами — проверить ударение'))
    return out


