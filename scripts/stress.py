    text = open(sys.argv[1], encoding='utf-8').read() if len(sys.argv) > 1 else sys.stdin.read()
    bad = check(text)
    for w, hint in bad:
        print(f'⚠ {w}: {hint}')
    print('ударения: всё помечено' if not bad else f'ударения: {len(bad)} слов без знака — поставить U+0301 или переформулировать')
    sys.exit(1 if bad else 0)
